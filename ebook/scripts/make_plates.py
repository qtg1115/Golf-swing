#!/usr/bin/env python3
"""Draw the cover art and the part-opener plates.

Every plate is drawn here rather than generated by an image model, so the book
carries no invented photographs and no burned-in lettering: all type is set in
WeasyPrint from book.yaml. The marks are the ones the author asked for — an
open circle for the cover, footprints on a broken path, a diagnostic grid, the
swing clock, three flight arcs, and a small index mark for the appendix.

The printed feel comes from simulating a lino/letterpress pull rather than from
a texture photograph: a shape is drawn at 3x, blurred into a soft edge field,
then thresholded against layered value noise so the ink bites unevenly, holds
sparse pinholes, and varies in pressure across the stroke. The seed is fixed,
so the same plates come out of every build.

Palette is locked to the paper cream, pine ink green, and charcoal in
templates/common.css.
"""
from __future__ import annotations

import math

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

from paths import IMAGES_DIR, REPO_ROOT

PAPER = (246, 243, 234)
PINE = (47, 92, 62)
CHARCOAL = (38, 44, 40)

# Part plates share the 3:2 proportion of the author's studies.
PLATE = (1500, 1000)
COVER = (1748, 2480)  # A5 at 300dpi
MARK = (460, 460)

SS = 3  # supersample factor for shape drawing


# --------------------------------------------------------------------------
# ink engine
# --------------------------------------------------------------------------


class Plate:
    """A sheet of paper that shapes can be pressed onto in one or more inks."""

    def __init__(
        self,
        size: tuple[int, int],
        seed: int,
        paper: bool = True,
        vignette: float = 0.0,
    ) -> None:
        self.w, self.h = size
        self.rng = np.random.default_rng(seed)
        self.opaque = paper
        if paper:
            self.rgb = self._paper(vignette)
            self.alpha = np.ones((self.h, self.w), dtype=np.float32)
        else:
            self.rgb = np.zeros((self.h, self.w, 3), dtype=np.float32)
            self.alpha = np.zeros((self.h, self.w), dtype=np.float32)

    # ---- noise -----------------------------------------------------------

    def _noise(self, cells: int) -> np.ndarray:
        """Smooth value noise: random lattice upsampled bicubically."""
        ch = max(2, int(cells * self.h / max(self.w, 1)))
        grid = (self.rng.random((ch, cells)) * 255).astype(np.uint8)
        up = Image.fromarray(grid, "L").resize((self.w, self.h), Image.BICUBIC)
        return np.asarray(up, dtype=np.float32) / 255.0

    def _paper(self, vignette: float) -> np.ndarray:
        """Cream stock: warm base and faint fibre.

        A part plate is drawn without any vignette so its edge dissolves into
        the cream page rather than printing as a visible rectangle. Only the
        full-bleed cover, which has no edge to hide, takes any shading.
        """
        base = np.zeros((self.h, self.w, 3), dtype=np.float32)
        base[:, :] = PAPER

        fibre = self._noise(max(40, self.w // 12)) - 0.5
        grain = self._noise(max(140, self.w // 4)) - 0.5
        sheet = base + (fibre * 6.0 + grain * 3.0)[:, :, None]

        if vignette:
            ys = np.linspace(-1.0, 1.0, self.h, dtype=np.float32)[:, None]
            xs = np.linspace(-1.0, 1.0, self.w, dtype=np.float32)[None, :]
            sheet = sheet * (1.0 - vignette * (xs**2 + ys**2))[:, :, None]

        return np.clip(sheet, 0, 255)

    # ---- drawing ---------------------------------------------------------

    def canvas(self) -> tuple[Image.Image, ImageDraw.ImageDraw]:
        img = Image.new("L", (self.w * SS, self.h * SS), 0)
        return img, ImageDraw.Draw(img)

    def press(
        self,
        shape: Image.Image,
        color: tuple[int, int, int],
        bite: float = 0.22,
        soften: int = 4,
        starve: float = 0.985,
        wear: float = 0.18,
    ) -> None:
        """Press one drawn mask onto the sheet as inked, imperfect coverage.

        `bite` is how far the noise is allowed to push the edge in and out,
        `starve` how rarely the ink lifts off entirely, and `wear` how much the
        lay-down thins across the sheet.
        """
        cov = shape.resize((self.w, self.h), Image.LANCZOS)
        soft = np.asarray(cov.filter(ImageFilter.GaussianBlur(soften)), dtype=np.float32) / 255.0

        # Edge roughness has to be fine-grained or it reads as a wobble rather
        # than as a cut block: most of the bite comes from a near-pixel lattice.
        tooth = 0.30 * self._noise(11) + 0.70 * self._noise(max(220, self.w // 5))
        field = soft - bite * (tooth - 0.5) * 2.0
        alpha = np.clip((field - 0.5) / 0.11 + 0.5, 0.0, 1.0)

        # Broad thin patches, the way a hand-pulled print loses ink unevenly.
        pressure = 0.6 * self._noise(8) + 0.4 * self._noise(24)
        alpha *= 1.0 - wear * np.clip(pressure - 0.42, 0, 1) * 2.0

        # A very few starved specks. Kept sparse and grey, never white confetti.
        speck = self._noise(max(260, self.w // 3))
        alpha = np.where(speck > starve, alpha * 0.55, alpha)
        alpha = np.clip(alpha, 0.0, 1.0)

        ink = np.zeros((self.h, self.w, 3), dtype=np.float32)
        ink[:, :] = color
        # Thin ink reads slightly lighter than a full lay-down.
        ink = ink + np.clip(0.62 - pressure, 0, 1)[:, :, None] * 26.0

        ink = np.clip(ink, 0, 255)
        if self.opaque:
            a = alpha[:, :, None]
            self.rgb = self.rgb * (1 - a) + ink * a
        else:
            # Straight alpha, so the ink colour has to be stored unmultiplied or
            # the soft edges wash out wherever the plate is laid over a page.
            fresh = (alpha > self.alpha)[:, :, None]
            self.rgb = np.where(fresh, ink, self.rgb)
        self.alpha = np.maximum(self.alpha, alpha)

    def save(self, name: str) -> None:
        """Write the plate.

        Paper grain is noise, and noise is the worst case for PNG, so an opaque
        plate ships as a JPEG: same look, a twentieth of the bytes.
        """
        dest = IMAGES_DIR / "plates" / name
        dest.parent.mkdir(parents=True, exist_ok=True)
        rgb = np.clip(self.rgb, 0, 255).astype(np.uint8)
        if dest.suffix == ".jpg":
            Image.fromarray(rgb, "RGB").save(dest, "JPEG", quality=92, optimize=True)
        else:
            rgba = np.dstack([rgb, (self.alpha * 255.0).astype(np.uint8)])
            Image.fromarray(rgba, "RGBA").save(dest, "PNG", optimize=True)
        print(f"  {dest.relative_to(REPO_ROOT)}  {self.w}x{self.h}  {dest.stat().st_size // 1024} KB")


# --------------------------------------------------------------------------
# stroke primitives, all in supersampled pixels
# --------------------------------------------------------------------------


def dot(draw: ImageDraw.ImageDraw, x: float, y: float, r: float) -> None:
    draw.ellipse([x - r, y - r, x + r, y + r], fill=255)


def arc(
    draw: ImageDraw.ImageDraw,
    cx: float,
    cy: float,
    r: float,
    a0: float,
    a1: float,
    w0: float,
    w1: float | None = None,
    gaps: tuple[tuple[float, float], ...] = (),
    steps: int = 900,
) -> None:
    """A brush-drawn arc whose nib tapers from w0 to w1, minus any gaps."""
    w1 = w0 if w1 is None else w1
    for i in range(steps + 1):
        u = i / steps
        if any(lo <= u <= hi for lo, hi in gaps):
            continue
        ang = math.radians(a0 + (a1 - a0) * u)
        dot(draw, cx + r * math.cos(ang), cy + r * math.sin(ang), w0 + (w1 - w0) * u)


def bezier(
    draw: ImageDraw.ImageDraw,
    p0: tuple[float, float],
    p1: tuple[float, float],
    p2: tuple[float, float],
    w0: float,
    w1: float | None = None,
    steps: int = 700,
) -> None:
    w1 = w0 if w1 is None else w1
    for i in range(steps + 1):
        u = i / steps
        x = (1 - u) ** 2 * p0[0] + 2 * (1 - u) * u * p1[0] + u**2 * p2[0]
        y = (1 - u) ** 2 * p0[1] + 2 * (1 - u) * u * p1[1] + u**2 * p2[1]
        dot(draw, x, y, w0 + (w1 - w0) * u)


def bar(
    draw: ImageDraw.ImageDraw,
    x0: float,
    y0: float,
    x1: float,
    y1: float,
    w: float,
    dashes: tuple[tuple[float, float], ...] = ((0.0, 1.0),),
) -> None:
    for lo, hi in dashes:
        for i in range(400):
            u = lo + (hi - lo) * i / 399
            dot(draw, x0 + (x1 - x0) * u, y0 + (y1 - y0) * u, w)


def rotate_about(
    pts: list[tuple[float, float]], cx: float, cy: float, rot: float
) -> list[tuple[float, float]]:
    ca, sa = math.cos(math.radians(rot)), math.sin(math.radians(rot))
    return [((x - cx) * ca - (y - cy) * sa + cx, (x - cx) * sa + (y - cy) * ca + cy) for x, y in pts]


# Half-width of a shoe sole down its length: toe, ball, waist, heel. Kept near
# 1:3 against the length, which is roughly what a real sole prints.
SOLE_T = (0.00, 0.05, 0.13, 0.24, 0.37, 0.50, 0.60, 0.70, 0.82, 0.93, 1.00)
SOLE_W = (0.050, 0.115, 0.152, 0.166, 0.158, 0.124, 0.104, 0.113, 0.137, 0.127, 0.055)


def footprint(
    draw: ImageDraw.ImageDraw,
    cx: float,
    cy: float,
    length: float,
    rot: float = 0.0,
) -> None:
    """A pressed shoe sole: ball and heel joined by a waist, split by a gap.

    Drawn as one outline so the two pads stay in register, then the arch band is
    lifted back out — which is what a real sole leaves on the ground.
    """
    top = cy - length / 2
    right = [
        (cx + length * np.interp(t, SOLE_T, SOLE_W), top + length * t) for t in np.linspace(0, 1, 90)
    ]
    left = [
        (cx - length * np.interp(t, SOLE_T, SOLE_W), top + length * t)
        for t in np.linspace(1, 0, 90)
    ]
    draw.polygon(rotate_about(right + left, cx, cy, rot), fill=255)

    # Lift the arch: a shoe prints the ball and the heel, not the bridge.
    band_y = top + length * 0.615
    half = length * 0.20
    gap = [
        (cx - half, band_y - length * 0.028),
        (cx + half, band_y - length * 0.028),
        (cx + half, band_y + length * 0.028),
        (cx - half, band_y + length * 0.028),
    ]
    draw.polygon(rotate_about(gap, cx, cy, rot), fill=0)


def arrowhead(
    draw: ImageDraw.ImageDraw,
    x: float,
    y: float,
    heading: float,
    length: float,
    half_width: float,
) -> None:
    """A triangle whose base sits at (x, y) and whose tip runs along heading."""
    a = math.radians(heading)
    along = (math.cos(a), math.sin(a))
    across = (-along[1], along[0])
    draw.polygon(
        [
            (x + length * along[0], y + length * along[1]),
            (x + half_width * across[0], y + half_width * across[1]),
            (x - half_width * across[0], y - half_width * across[1]),
        ],
        fill=255,
    )


