def cover_art() -> None:
    """Full-bleed cover stock with the open circle low on the page.

    Type is not drawn here. The arc sits in the lower half so the title,
    subtitle and byline set in CSS have quiet paper to stand on.
    """
    plate = Plate(COVER, seed=1101, vignette=0.05)
    w, h = plate.w * SS, plate.h * SS
    img, draw = plate.canvas()

    cx, cy, r = w * 0.5, h * 0.605, w * 0.232
    # One brush sweep that never closes: thin where the stroke lands, heaviest
    # through the bottom left, thin again as it lifts. Two passes because the
    # nib only tapers one way per pass.
    arc(draw, cx, cy, r, 96, 268, w * 0.0098, w * 0.0205)
    arc(draw, cx, cy, r, 268, 398, w * 0.0205, w * 0.0062)
    # A second, wider sweep past the opening — the arc the swing actually travels.
    arc(draw, cx, cy, r * 1.15, 26, 122, w * 0.0140, w * 0.0020)
    plate.press(img, PINE, bite=0.19, soften=6, starve=0.988)
    plate.save("cover-art.jpg")


def part1_footprints() -> None:
    """1부 — two prints standing on a path that breaks up as it turns."""
    plate = Plate(PLATE, seed=2201)
    w, h = plate.w * SS, plate.h * SS

    img, draw = plate.canvas()
    # The path sweeps in from the left, curls round behind the feet and breaks up.
    arc(
        draw,
        w * 0.44,
        h * 0.575,
        w * 0.26,
        -152,
        58,
        w * 0.0125,
        w * 0.0105,
        gaps=((0.13, 0.165), (0.30, 0.335), (0.47, 0.505), (0.64, 0.675), (0.81, 0.845)),
    )
    bar(
        draw,
        w * 0.03,
        h * 0.895,
        w * 0.42,
        h * 0.895,
        w * 0.0115,
        dashes=((0.0, 0.45), (0.55, 0.88), (0.95, 1.0)),
    )
    plate.press(img, PINE, bite=0.24, soften=5)

    img, draw = plate.canvas()
    footprint(draw, w * 0.415, h * 0.585, h * 0.42, rot=-7.0)
    footprint(draw, w * 0.545, h * 0.475, h * 0.42, rot=-13.0)
    plate.press(img, CHARCOAL, bite=0.20, soften=4, starve=0.992)
    plate.save("part-1-footprints.jpg")


def part2_grid() -> None:
    """2부 — an empty diagnostic grid with one cell stamped.

    Deliberately not a photograph and not a filled table: the part is about
    finding which cell your own miss lands in.
    """
    plate = Plate(PLATE, seed=3301)
    w, h = plate.w * SS, plate.h * SS
    cols, rows = 4, 3
    x0, y0 = w * 0.13, h * 0.20
    cw, ch = (w * 0.74) / cols, (h * 0.60) / rows

    img, draw = plate.canvas()
    for c in range(cols + 1):
        bar(draw, x0 + c * cw, y0, x0 + c * cw, y0 + rows * ch, w * 0.0035)
    for r in range(rows + 1):
        bar(draw, x0, y0 + r * ch, x0 + cols * cw, y0 + r * ch, w * 0.0035)
    plate.press(img, CHARCOAL, bite=0.15, soften=3, starve=0.986)

    img, draw = plate.canvas()
    # One cell is answered; the rest wait for the reader's own assessment.
    ccx, ccy = x0 + cw * 2.5, y0 + ch * 1.5
    arc(draw, ccx, ccy, min(cw, ch) * 0.36, 0, 360, w * 0.0052)
    plate.press(img, PINE, bite=0.28, soften=6)
    plate.save("part-2-grid.jpg")


def part3_clock() -> None:
    """3부 — the swing clock: a dial with the down-and-through sweep in green."""
    plate = Plate(PLATE, seed=4401)
    w, h = plate.w * SS, plate.h * SS
    cx, cy, r = w * 0.5, h * 0.5, h * 0.335

    img, draw = plate.canvas()
    arc(draw, cx, cy, r, 0, 360, w * 0.0095)
    for angle in (270, 0, 90, 180):
        a = math.radians(angle)
        bar(
            draw,
            cx + r * 0.845 * math.cos(a),
            cy + r * 0.845 * math.sin(a),
            cx + r * 0.955 * math.cos(a),
            cy + r * 0.955 * math.sin(a),
            w * 0.0075,
        )
    plate.press(img, CHARCOAL, bite=0.30, soften=6)

    img, draw = plate.canvas()
    # Down to six o'clock and back up: the path the book keeps returning to.
    # Both ends carry a head, because the reader travels the arc in both halves.
    left_end = (cx - r * 0.52, cy - r * 0.40)
    low = (cx + r * 0.02, cy + r * 0.58)
    right_end = (cx + r * 0.66, cy - r * 0.32)
    bezier(draw, left_end, (cx - r * 0.60, cy + r * 0.34), low, w * 0.0080, w * 0.0110)
    bezier(draw, low, (cx + r * 0.62, cy + r * 0.44), right_end, w * 0.0110, w * 0.0078)
    arrowhead(draw, left_end[0], left_end[1], -104, w * 0.040, w * 0.026)
    arrowhead(draw, right_end[0], right_end[1], -62, w * 0.040, w * 0.026)
    plate.press(img, PINE, bite=0.20, soften=5)
    plate.save("part-3-clock.jpg")


def part4_arcs() -> None:
    """4부 — three ball flights off one launch point. No labels: the chapters name them."""
    plate = Plate(PLATE, seed=5501)
    w, h = plate.w * SS, plate.h * SS
    ground = h * 0.845
    launch = (w * 0.105, ground)

    img, draw = plate.canvas()
    bar(draw, w * 0.02, ground, w * 0.98, ground, w * 0.0045)
    plate.press(img, CHARCOAL, bite=0.34, soften=8, starve=0.88, wear=0.34)

    img, draw = plate.canvas()
    flights = (
        ((w * 0.52, h * 0.030), (w * 0.905, h * 0.545)),
        ((w * 0.50, h * 0.300), (w * 0.930, h * 0.660)),
        ((w * 0.48, h * 0.590), (w * 0.955, h * 0.775)),
    )
    for control, end in flights:
        bezier(draw, launch, control, end, w * 0.0032)
        dot(draw, end[0], end[1], w * 0.0075)
    plate.press(img, CHARCOAL, bite=0.11, soften=2, starve=0.995, wear=0.10)
    plate.save("part-4-arcs.jpg")


def figure_hi_launch() -> None:
    """4부 챕터 3 — one high launch and a short landing.

    Replaces a photoreal golfer on a mountain course. No person, no face, no
    fairway, no club: the chapter is about the shape of the flight, so the plate
    draws only the flight.
    """
    # Shorter frame than a part plate: this one sits inline, so it should not
    # carry a part opener's worth of empty paper.
    plate = Plate((1500, 820), seed=7701)
    w, h = plate.w * SS, plate.h * SS
    ground = h * 0.90
    launch = (w * 0.20, ground)

    img, draw = plate.canvas()
    bar(draw, w * 0.04, ground, w * 0.96, ground, w * 0.0045)
    plate.press(img, CHARCOAL, bite=0.34, soften=8, starve=0.88, wear=0.34)

    img, draw = plate.canvas()
    # The control sits above the frame so the flight actually climbs: a quadratic
    # only reaches halfway to its control point.
    end = (w * 0.80, ground)
    bezier(draw, launch, (w * 0.50, -h * 0.30), end, w * 0.0034)
    # It lands steeply and stops, so the mark ends on the ground.
    dot(draw, end[0], end[1] - h * 0.008, w * 0.0075)
    plate.press(img, CHARCOAL, bite=0.11, soften=2, starve=0.995, wear=0.10)
    plate.save("fig-hi-launch.jpg")


def play_mark() -> None:
    """Small ink poster for EPUB video slots: the cover's open circle + a triangle.

    Drawn, not generated. No person, no club, no course. Print does not use it.
    """
    # Cream stock, not transparency: many reading systems ignore PNG alpha and
    # would otherwise print a black square behind the mark.
    plate = Plate((640, 640), seed=8801, paper=True)
    w, h = plate.w * SS, plate.h * SS
    cx, cy, r = w * 0.5, h * 0.5, w * 0.34

    img, draw = plate.canvas()
    # Same language as the cover: one sweep that never closes.
    arc(draw, cx, cy, r, 108, 428, w * 0.014, w * 0.008)
    plate.press(img, PINE, bite=0.20, soften=5, starve=0.99)

    img, draw = plate.canvas()
    # Play triangle in the opening, pointing through the gap.
    arrowhead(draw, cx - w * 0.03, cy, 0, w * 0.16, w * 0.11)
    plate.press(img, PINE, bite=0.22, soften=4)
    plate.save("play-mark.png")


def appendix_mark() -> None:
    """부록 — a small index mark, nothing figurative.

    Ink on transparency rather than on stock: the appendix runs on white text
    pages, so the mark has to sit on whatever the page is.
    """
    plate = Plate(MARK, seed=6601, paper=False)
    w, h = plate.w * SS, plate.h * SS

    img, draw = plate.canvas()
    bar(draw, w * 0.30, h * 0.24, w * 0.30, h * 0.76, w * 0.022)
    bar(draw, w * 0.30, h * 0.24, w * 0.52, h * 0.24, w * 0.022)
    bar(draw, w * 0.30, h * 0.76, w * 0.52, h * 0.76, w * 0.022)
    dot(draw, w * 0.68, h * 0.50, w * 0.055)
    plate.press(img, PINE, bite=0.26, soften=5)
    plate.save("appendix-mark.png")


def main() -> int:
    print("plates")
    cover_art()
    part1_footprints()
    part2_grid()
    part3_clock()
    part4_arcs()
    figure_hi_launch()
    appendix_mark()
    play_mark()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
